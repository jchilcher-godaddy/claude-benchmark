"""Token efficiency calculator for claude-benchmark.

Computes quality-per-token and quality-per-dollar metrics to measure how
efficiently a model uses tokens to produce quality output.
"""

from __future__ import annotations

from claude_benchmark.execution.cost import compute_cost, cost_breakdown

from .models import TokenEfficiency


def compute_token_efficiency(
    composite_score: float,
    claudemd_context_tokens: int,
    task_io_tokens: int,
    *,
    input_tokens: int = 0,
    output_tokens: int = 0,
    cache_creation_input_tokens: int = 0,
    cache_read_input_tokens: int = 0,
    model: str = "",
) -> TokenEfficiency:
    """Compute token efficiency from a composite score and token counts.

    Args:
        composite_score: The composite quality score (0-100).
        claudemd_context_tokens: Tokens consumed by CLAUDE.md context.
        task_io_tokens: Tokens consumed by task input/output.
        input_tokens: Fresh (uncached) input tokens sent to the model.
        output_tokens: Output tokens generated by the model.
        cache_creation_input_tokens: Tokens written to prompt cache (priced 1.25x input).
        cache_read_input_tokens: Tokens read from prompt cache (priced 0.10x input).
        model: Model name for pricing lookup (e.g. "haiku", "sonnet", "opus").

    Returns:
        TokenEfficiency with all fields populated, including a per-category
        cost breakdown that can be summed to verify cost_usd.
    """
    total_tokens = claudemd_context_tokens + task_io_tokens

    if total_tokens == 0:
        points_per_1k = 0.0
    else:
        points_per_1k = round((composite_score / total_tokens) * 1000, 2)

    cost_usd = 0.0
    breakdown: dict[str, float] = {}
    points_per_dollar = 0.0

    any_tokens = (
        input_tokens > 0
        or output_tokens > 0
        or cache_creation_input_tokens > 0
        or cache_read_input_tokens > 0
    )
    if any_tokens:
        cost_usd = compute_cost(
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            cache_creation_input_tokens=cache_creation_input_tokens,
            cache_read_input_tokens=cache_read_input_tokens,
            model=model,
        )
        raw_breakdown = cost_breakdown(
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            cache_creation_input_tokens=cache_creation_input_tokens,
            cache_read_input_tokens=cache_read_input_tokens,
            model=model,
        )
        breakdown = {k: round(v, 6) for k, v in raw_breakdown.items()}
        if cost_usd > 0:
            points_per_dollar = round(composite_score / cost_usd, 2)

    return TokenEfficiency(
        composite_score=composite_score,
        total_tokens=total_tokens,
        claudemd_tokens=claudemd_context_tokens,
        task_io_tokens=task_io_tokens,
        points_per_1k_tokens=points_per_1k,
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        cache_creation_input_tokens=cache_creation_input_tokens,
        cache_read_input_tokens=cache_read_input_tokens,
        cost_usd=round(cost_usd, 6),
        cost_breakdown_usd=breakdown,
        points_per_dollar=points_per_dollar,
        model=model,
    )
